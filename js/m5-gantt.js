/* Модуль 5, занятие 12 (облегчённое): диаграмма Ганта.
   Теория: how-gt-parts — полосы работ, зависимости, вехи, критический путь на плане второго релиза «Искры»;
   how-gt-cp — как найти критический путь и резерв, код Mermaid и PlantUML.
   Практика: лаборатория «что сдвинется» (расчёт по плану, не по догадке); что это за элемент; ответ Тимуру. */
